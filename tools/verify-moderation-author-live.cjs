const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const { expect } = require((process.env.PLAYWRIGHT_PACKAGE || 'playwright') + '/test');
const { api } = require('./verify-creator-comment-controls-live.cjs');
const { login } = require('./verify-be10-live.cjs');
const { mkdir, writeFile } = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const output = path.resolve('../moderation-author-acceptance');
let browser, owner, postId;
async function main() {
  await mkdir(output,{recursive:true});
  await expect.poll(async()=>{try{return (await fetch('http://localhost:3000/health')).ok;}catch{return false;}},{timeout:60000}).toBe(true);
  const password=process.env.CREATOR_QA_PASSWORD?.trim();assert.ok(password);
  const signIn=async email=>(await api('/auth/login',null,'POST',{email,password})).accessToken;
  const [member,writer,staff]=await Promise.all(['member@tripflix.local','moderator@tripflix.local','superadmin@tripflix.local'].map(signIn));
  owner=member;
  postId=(await api('/v1/posts',owner,'POST',{post_type:'vlog',title:'QA thông tin người bình luận '+Date.now(),body:'Bài kiểm tra thông tin tác giả trong Admin.'},201)).id;
  await api(`/v1/posts/${postId}/publish`,owner,'POST',undefined,201);
  const root=await api(`/v1/posts/${postId}/comments`,owner,'POST',{body:'Bình luận gốc QA của chủ bài.'},201);
  const comment=await api(`/v1/posts/${postId}/comments`,writer,'POST',{body:'Bình luận QA xác minh tên và email tác giả.',parent_comment_id:root.id},201);
  const report=await api(`/v1/comments/${comment.id}/reports`,staff,'POST',{reasonCode:'OTHER'},201);
  const detail=await api(`/v1/admin/moderation/queue/${report.caseId}`,staff);
  const identity=await api('/auth/me',writer);
  const user=identity.user??identity;
  assert.deepEqual(detail.author,{id:comment.authorId,displayName:user.displayName,email:user.email});
  const ownerIdentity=await api('/auth/me',owner);
  const postOwner=ownerIdentity.user??ownerIdentity;
  assert.notEqual(detail.author.id,postOwner.id);
  assert.equal(detail.postContext.id,postId);
  assert.deepEqual(detail.postContext.author,{id:postOwner.id,displayName:postOwner.displayName,email:postOwner.email});
  assert.equal(detail.parentComment.id,root.id);
  assert.equal(detail.parentComment.body,root.body);
  assert.ok(!Object.hasOwn(detail.author,'passwordHash'));
  await api(`/v1/admin/moderation/queue/${report.caseId}`,null,'GET',undefined,401);
  await api(`/v1/admin/moderation/queue/${report.caseId}`,owner,'GET',undefined,403);
  const publicComments=await api(`/v1/posts/${postId}/comments`,null);
  assert.ok(!JSON.stringify(publicComments).includes(user.email));
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  await login(page,'superadmin@tripflix.local',comment.id);
  const context=page.getByRole('region',{name:'Bài đăng chứa bình luận',exact:true});
  await expect(context.getByText(postOwner.email,{exact:true})).toBeVisible();
  await expect(context.locator('dl').getByText(postOwner.displayName,{exact:true})).toBeVisible();
  await expect(context.getByText(root.body,{exact:true})).toBeVisible();
  const link=context.getByRole('link',{name:'Mở bài đăng gốc',exact:false});
  const href=new URL(await link.getAttribute('href'));
  assert.equal(href.searchParams.get('open'),postId);
  assert.equal(href.searchParams.get('comment'),comment.id);
  const popupPromise=page.waitForEvent('popup');
  await link.click();
  const popup=await popupPromise;
  await popup.waitForLoadState('domcontentloaded',{timeout:60000});
  assert.equal(new URL(popup.url()).searchParams.get('open'),postId);
  await expect(popup.getByText(detail.postContext.title,{exact:true}).first()).toBeVisible({timeout:30000});
  await popup.close();
  const section=page.getByRole('region',{name:'Người bình luận',exact:true});
  await expect(section.getByText(user.displayName,{exact:true})).toBeVisible();
  await expect(section.getByText(user.email,{exact:true})).toBeVisible();
  await expect(section.getByText(comment.authorId,{exact:true})).toBeVisible();
  for(const width of [1440,390]) {
    await page.setViewportSize({width,height:1080});
    await context.getByRole('heading',{name:'Bài đăng chứa bình luận',exact:true}).scrollIntoViewIfNeeded();
    assert.ok(await context.evaluate(node=>node.scrollWidth<=node.clientWidth));
    await page.screenshot({path:path.join(output,`comment-context-${width}.png`)});
    await section.scrollIntoViewIfNeeded();
    const fits=await section.evaluate(node=>node.scrollWidth<=node.clientWidth);
    assert.ok(fits,`Author card fits ${width}px`);
    await page.screenshot({path:path.join(output,`comment-author-${width}.png`)});
  }
  await writeFile(path.join(output,'result.json'),JSON.stringify({result:'passed',checks:['real comment author differs from post owner','name + registered email + full account ID visible in Admin','member/guest blocked','public comments have no email','1440/390 no horizontal overflow','source post owner and reply context','opens original post and exact comment in Web']},null,2));
  process.stdout.write('Moderation author Admin/API acceptance passed\n');
}
main().catch(async error=>{
  if(browser)for(const context of browser.contexts())for(const page of context.pages())await page.screenshot({path:path.join(output,'failure.png')}).catch(()=>{});
  process.stderr.write(String(error.stack||error));process.exitCode=1;
}).finally(async()=>{await browser?.close();if(owner&&postId)await api(`/v1/posts/${postId}`,owner,'DELETE').catch(()=>{});});
